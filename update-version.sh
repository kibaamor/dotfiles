SKIP_VERSIONS=0
MAX_JOBS=8

while getopts "sj:h" opt; do
  case "$opt" in
    s) SKIP_VERSIONS=1 ;;
    j) MAX_JOBS="$OPTARG" ;;
    h)
      cat >&2 <<'USAGE'
Usage: ./update-version.sh [-s] [-j N]

Options:
  -s                    Skip GitHub API calls; reuse existing versions.yaml on disk.
  -j N                  Max concurrent jobs (default: 8).
  -h                    Show this help message.
USAGE
      exit 0
      ;;
    *)
      echo "usage: ./update-version.sh [-s] [-j N] [-h]" >&2
      exit 1
      ;;
  esac
done
shift $((OPTIND - 1))

if [[ ! "$MAX_JOBS" =~ ^[1-9][0-9]*$ ]]; then
  echo "error: -j must be a positive integer: $MAX_JOBS" >&2
  exit 1
fi

declare -A NEW_VERSIONS=()
declare -A NEW_COMMITS=()
declare -A CHECKSUM_CACHE=()
declare -A NEW_CHECKSUMS=()
declare -a URLS=()
declare -a WORK_DIRS=()
RUNNING=0
SPAWN_FAILURES=0

die() {
  echo "error: $*" >&2
  exit 1
}

require_command() {
  command -v "$1" >/dev/null 2>&1 || die "required command not found: $1"
}

new_work_dir() {
  TMP_DIR="$(mktemp -d "$ROOT_DIR/$1.XXXXXX")"
  WORK_DIRS+=("$TMP_DIR")
}

cleanup_work_dirs() {
  local dir
  for dir in "${WORK_DIRS[@]}"; do
    rm -rf "$dir"
  done
}
trap cleanup_work_dirs EXIT

spawn() {
  "$@" &
  RUNNING=$((RUNNING + 1))
  while ((RUNNING >= MAX_JOBS)); do
    if wait -n; then
      RUNNING=$((RUNNING - 1))
    else
      status=$?
      if ((status > 128)); then
        die "interrupted by signal $((status - 128))"
      fi
      RUNNING=$((RUNNING - 1))
      SPAWN_FAILURES=$((SPAWN_FAILURES + 1))
    fi
  done
}

drain() {
  local status
  local failures=$SPAWN_FAILURES
  SPAWN_FAILURES=0
  while ((RUNNING > 0)); do
    if wait -n; then
      RUNNING=$((RUNNING - 1))
    else
      status=$?
      if ((status > 128)); then
        die "interrupted by signal $((status - 128))"
      fi
      RUNNING=$((RUNNING - 1))
      failures=$((failures + 1))
    fi
  done
  ((failures == 0))
}

load_existing_versions() {
  local key line value
  local section=""

  [[ -f "$VERSIONS_FILE" ]] || return

  # The files are generated by this script, so a lightweight parser is enough
  # and avoids adding a YAML dependency just to read simple top-level maps.
  while IFS= read -r line; do
    case "$line" in
    "versions:")
      section="versions"
      ;;
    "commits:")
      section="commits"
      ;;
    "  "*": "*)
      key="${line%%:*}"
      key="${key#"${key%%[![:space:]]*}"}"
      value="${line#*: }"
      case "$section" in
      versions)
        NEW_VERSIONS["$key"]="$value"
        ;;
      commits)
        NEW_COMMITS["$key"]="$value"
        ;;
      esac
      ;;
    esac
  done <"$VERSIONS_FILE"
}

load_existing_checksums() {
  local key line value

  [[ -f "$CHECKSUMS_FILE" ]] || return

  while IFS= read -r line; do
    [[ "$line" == '  "'*'": "'*'"' ]] || continue
    key="${line#  \"}"
    key="${key%%\": \"*}"
    value="${line##*\": \"}"
    value="${value%\"}"
    CHECKSUM_CACHE["$key"]="$value"
  done <"$CHECKSUMS_FILE"
}

latest_version_for() {
  local repo="$1"
  local version
  version="$(
    { gh release view --repo "$repo" --json tagName --jq '.tagName' 2>/dev/null \
      || gh api --jq '.[0].name // empty' "repos/$repo/tags" 2>/dev/null; } \
      | sed -nE 's/^[^0-9]*([0-9]+([.][0-9]+)*)$/\1/p'
  )" || version=""
  [[ "$version" =~ ^[0-9]+([.][0-9]+)*$ ]] || version=""
  echo "$version"
}

latest_commit_for() {
  local repo="$1"
  local ref="$2"

  gh api \
    --method GET \
    --header 'Accept: application/vnd.github+json' \
    --jq '.sha' \
    "https://api.github.com/repos/$repo/commits/$ref"
}

version_key_for() {
  echo "$1" | cut -d '/' -f 2 | tr -d '-'
}

canonical_key_for_url() {
  local url="$1"

  url="${url#https://}"
  url="${url#cdn.gh-proxy.org/https://}"
  echo "$url"
}

report_change() {
  local label="$1" new_val="$2" old_val="$3"

  if [[ -n "$old_val" && "$old_val" == "$new_val" ]]; then
    echo "$label unchanged ($new_val)"
  else
    echo "$label updated (${old_val:-none} -> $new_val)"
  fi
}

fetch_version_job() {
  local out_file="$1" repo="$2" version

  version="$(latest_version_for "$repo")"
  printf '%s' "$version" >"$out_file"
}

fetch_commit_job() {
  local out_file="$1" repo="$2" ref="$3" commit

  commit="$(latest_commit_for "$repo" "$ref" 2>/dev/null)"
  [[ "$commit" =~ ^[0-9a-f]{40}$ ]] || commit=""
  printf '%s' "$commit" >"$out_file"
}

# resolve_all <job_fn> <map_name> <label> <prefix_msg> <spec>...
# Each spec is "<repo> <ref> <key>"; ref is ignored by version jobs.
resolve_all() {
  local job_fn="$1" map_name="$2" label="$3" prefix_msg="$4"
  shift 4
  # shellcheck disable=SC2178
  local -n dest_map="$map_name"
  local tmp_dir idx=0 repo ref key item failures=0
  local -a results=()

  new_work_dir ".update-version-resolve"
  tmp_dir="$TMP_DIR"
  for item in "$@"; do
    read -r repo ref _ <<<"$item"
    spawn "$job_fn" "$tmp_dir/$idx" "$repo" "$ref"
    ((idx++))
  done
  drain || true

  idx=0
  for item in "$@"; do
    results+=("$(cat "$tmp_dir/$idx" 2>/dev/null)")
    ((idx++))
  done

  idx=0
  for item in "$@"; do
    read -r repo _ key <<<"$item"
    printf '%s%s ... ' "$prefix_msg" "$repo"
    if [[ -z "${results[$idx]}" ]]; then
      echo "failed"
      failures=$((failures + 1))
    else
      report_change "$label" "${results[$idx]}" "${dest_map[$key]:-}"
      dest_map["$key"]="${results[$idx]}"
    fi
    ((idx++))
  done
  ((failures == 0)) || die "failed to resolve $label for $failures repo(s)"
}

build_versions_body() {
  local repo key spec

  echo "versions:"
  for repo in "${repos[@]}"; do
    key="$(version_key_for "$repo")"
    echo "  # https://github.com/$repo"
    echo "  $key: ${NEW_VERSIONS[$key]}"
  done

  echo
  echo "commits:"

  for spec in "${commit_repos[@]}"; do
    read -r repo _ key <<<"$spec"
    echo "  # https://github.com/$repo"
    echo "  $key: ${NEW_COMMITS[$key]}"
  done
}

build_checksums_body() {
  local key

  echo "checksums:"
  while IFS= read -r key; do
    printf '  "%s": "%s"\n' "$key" "${NEW_CHECKSUMS[$key]}"
  done < <(printf '%s\n' "${!NEW_CHECKSUMS[@]}" | sort)
}

write_generated_file() {
  local output_file="$1" body="$2"

  if [[ -f "$output_file" && "$body" == "$(tail -n +4 "$output_file")" ]]; then
    return 2
  fi

  {
    echo "# Auto-generated by ./update-version.sh — DO NOT EDIT"
    echo "# Generated at: $(date -u +"%Y-%m-%dT%H:%M:%SZ")"
    echo
    printf '%s\n' "$body"
  } >"$output_file" || die "failed to write $output_file"
}

write_json_object() {
  # shellcheck disable=SC2178
  local map_name="$1" key sep=""
  # shellcheck disable=SC2178
  local -n map_ref="$map_name"
  local -a keys=()

  printf '{'
  if ((${#map_ref[@]} > 0)); then
    mapfile -t keys < <(printf '%s\n' "${!map_ref[@]}" | sort)
    for key in "${keys[@]}"; do
      printf '%s"%s":"%s"' "$sep" "$key" "${map_ref[$key]}"
      sep=","
    done
  fi
  printf '}'
}

render_override_data() {
  local os="$1" arch="$2"

  printf '{"chezmoi":{"os":"%s","arch":"%s"},"versions":' "$os" "$arch"
  write_json_object NEW_VERSIONS
  printf ',"commits":'
  write_json_object NEW_COMMITS
  printf ',"checksums":'
  write_json_object CHECKSUM_CACHE
  printf '}'
}

extract_urls() {
  sed -n -e 's/^[[:space:]]*url:[[:space:]]*"\(.*\)"[[:space:]]*$/\1/p' \
         -e 's/^[[:space:]]*-[[:space:]]*"\(.*\)"[[:space:]]*$/\1/p' \
    | grep -F '://' \
    | sort -u
}

render_target_urls() {
  local target="$1" out_file="$2"
  local os arch data config skill_suit rc=0

  os="${target%/*}"
  arch="${target#*/}"
  data="$(render_override_data "$os" "$arch")"

  config="$(env DOTFILES_EXTRA_BINS=1 DOTFILES_ARKADE_BINS=1 DOTFILES_MIRROR= \
    chezmoi --source "$ROOT_DIR" execute-template \
    --override-data "$data" \
    --file "$CONFIG_TEMPLATE")"

  # Include URLs for every selectable agent skill suite.
  for skill_suit in matt superpowers; do
    env DOTFILES_EXTRA_BINS=1 DOTFILES_ARKADE_BINS=1 DOTFILES_MIRROR= \
      "DOTFILES_AGENT_SKILL_SUIT=$skill_suit" \
      chezmoi --source "$ROOT_DIR" \
      --config <(printf '%s\n' "$config") \
      --config-format yaml \
      execute-template \
      --override-data "$data" \
      --file "$EXTERNALS_TEMPLATE" \
      | extract_urls >>"$out_file" || rc=1
  done
  return "$rc"
}

collect_urls() {
  local tmp_dir target

  new_work_dir .update-version-render
  local tmp_dir="$TMP_DIR"
  for target in "${targets[@]}"; do
    spawn render_target_urls "$target" "$tmp_dir/${target//\//-}"
  done
  drain || die "failed to render download URLs"

  mapfile -t URLS < <(cat "$tmp_dir"/* 2>/dev/null | sort -u)
}

checksum_job() {
  local out_file="$1" key="$2" url="$3" sha256

  if [[ -n "${CHECKSUM_CACHE[$key]:-}" ]]; then
    echo "cached checksum: $url" >&2
    printf '%s|%s\n' "$key" "${CHECKSUM_CACHE[$key]}" >"$out_file"
    return
  fi

  echo "checksumming: $url" >&2
  if sha256="$(curl --fail --silent --show-error --location --retry 3 "$url" | sha256sum | awk '{print $1}')" && [[ -n "$sha256" ]]; then
    printf '%s|%s\n' "$key" "$sha256" >"$out_file"
  else
    echo "error: failed to checksum URL: $url" >&2
    printf '%s|FAIL\n' "$key" >"$out_file"
  fi
}

update_checksums() {
  local tmp_dir idx=0 key url sha256 failures=0
  local -A seen=()

  collect_urls
  ((${#URLS[@]} > 0)) || die "no download URLs rendered"

  new_work_dir .update-version-checksums
  local tmp_dir="$TMP_DIR"
  for url in "${URLS[@]}"; do
    key="$(canonical_key_for_url "$url")"
    [[ -n "${seen[$key]+x}" ]] && continue
    seen["$key"]=1
    spawn checksum_job "$tmp_dir/$idx" "$key" "$url"
    ((idx++))
  done
  drain || true

  while IFS='|' read -r key sha256; do
    if [[ "$sha256" == "FAIL" ]]; then
      failures=$((failures + 1))
      continue
    fi
    NEW_CHECKSUMS["$key"]="$sha256"
  done < <(cat "$tmp_dir"/* 2>/dev/null)

  ((failures == 0)) || die "$failures URL(s) failed to checksum"
  ((${#NEW_CHECKSUMS[@]} == ${#seen[@]})) || die "missing checksums for some URLs"
}

main() {
  require_command chezmoi
  require_command curl
  require_command gh
  require_command sha256sum

  local repo
  local -a version_specs=()

  load_existing_versions

  if ((SKIP_VERSIONS)); then
    ((${#NEW_VERSIONS[@]} > 0)) || die "no existing versions.yaml to reuse, run without -s first"
  else
    for repo in "${repos[@]}"; do
      version_specs+=("$repo v $(version_key_for "$repo")")
    done
    resolve_all fetch_version_job NEW_VERSIONS version "processing repo: " "${version_specs[@]}"
    resolve_all fetch_commit_job NEW_COMMITS commit "processing repo commit: " "${commit_repos[@]}"
    write_generated_file "$VERSIONS_FILE" "$(build_versions_body)"
    if (( $? == 2 )); then
      echo "versions unchanged, skipping write: $VERSIONS_FILE" >&2
    fi
  fi

  load_existing_checksums
  update_checksums
  write_generated_file "$CHECKSUMS_FILE" "$(build_checksums_body)"
  if (( $? == 2 )); then
    echo "checksums unchanged, skipping write: $CHECKSUMS_FILE" >&2
  fi
}

main
